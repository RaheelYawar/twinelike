/*
 * build-feature-coverage-html.js
 * --------------------------------
 * Assembles TestFiles/feature-coverage.twee into a self-contained, runnable
 * *reference-Harlowe* HTML (TestFiles/feature-coverage-harlowe.html) — the same way
 * Twine/tweego publishes a Harlowe story: template.html with {{CSS}} / {{HARLOWE}}
 * / {{STORY_DATA}} / {{STORY_NAME}} substituted. Open the output in any browser to
 * capture ground-truth output for validating the C# library against real Harlowe.
 *
 * It adds a generated "_Index" start passage linking to every feature passage, so
 * each can be visited (click a link; use the sidebar undo arrow to return). The
 * .twee's own start passage ("Start") is left intact and is reachable from the index.
 *
 * REPRODUCE (the engine build lives under references/, which is gitignored — see
 * CLAUDE.md "Spec & reference sources"; download/unzip the branch-default archive first):
 *   cd references/harlowe-branch-default/harlowe-branch-default
 *   npm install
 *   ./node_modules/.bin/rollup -c rollup.config.js                 # -> build/harlowe-min.js
 *   cat scss/*.scss | ./node_modules/.bin/sass --stdin --style compressed > build/harlowe-css.css
 *   node ../../../TestFiles/build-feature-coverage-html.js . \
 *        ../../../TestFiles/feature-coverage.twee \
 *        ../../../TestFiles/feature-coverage-harlowe.html
 *
 * The embedded engine is the locally-built branch/default Harlowe (4.0.0-unstable
 * ~= v3.3.8+67) — the same reference this project cites for macro semantics. Its exact
 * node id is recorded in the generated file's leading HTML comment (.hg_archival.txt).
 */
'use strict';
const fs = require('fs');
const path = require('path');

const [REFDIR, TWEE, OUT] = process.argv.slice(2);
if (!REFDIR || !TWEE || !OUT) {
  console.error('usage: node build-feature-coverage-html.js <refBuildDir> <twee> <outHtml>');
  process.exit(1);
}

const escAttr = s => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const escBody = s => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// --- Parse the Twee file: split on `:: ` headers at column 0 ---
const raw = fs.readFileSync(TWEE, 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n');
const blocks = [];
let cur = null;
for (const line of raw.split('\n')) {
  const m = /^:: (.+)$/.exec(line);
  if (m) blocks.push(cur = { name: m[1].trim(), body: [] });
  else if (cur) cur.body.push(line);
}
for (const b of blocks) b.body = b.body.join('\n').replace(/[\r\n]+$/, ''); // match TweeReader's TrimEnd('\r','\n')

let storyName = 'Harlowe Feature Coverage', ifid = '', startName = 'Start';
const passages = [];
for (const b of blocks) {
  if (b.name === 'StoryTitle') { storyName = b.body.trim(); continue; }
  if (b.name === 'StoryData') {
    try { const j = JSON.parse(b.body); if (j.ifid) ifid = j.ifid; if (j.start) startName = j.start; }
    catch (e) { console.error('StoryData JSON parse failed:', e.message); }
    continue;
  }
  passages.push(b);
}

// --- Build the navigation index (the start passage) ---
const featureNames = passages.map(p => p.name).slice().sort(); // matches the C# harness ordering closely
const indexBody =
  'Harlowe feature-coverage harness — reference output.\n' +
  'Click a passage to see how real Harlowe renders it; use the sidebar ↶ undo arrow to return here.\n\n' +
  featureNames.map(n => '[[' + n + ']]').join('\n');

// pids: feature passages 1..N in file order; index gets N+1 and is the startnode.
const pidOf = new Map();
let pid = 0;
for (const p of passages) pidOf.set(p.name, ++pid);
const indexPid = ++pid;

const tpd = (id, name, body, tags) =>
  `<tw-passagedata pid="${id}" name="${escAttr(name)}" tags="${escAttr(tags || '')}" position="0,0" size="100,100">${escBody(body)}</tw-passagedata>\n`;
let sd = tpd(indexPid, '_Index', indexBody, 'coverage-index');
for (const p of passages) sd += tpd(pidOf.get(p.name), p.name, p.body, '');

const storydata =
  `<tw-storydata name="${escAttr(storyName)}" startnode="${indexPid}" ` +
  `creator="twinelike feature-coverage harness" creator-version="1.0" ` +
  `format="Harlowe" format-version="4.0.0" ` +
  `ifid="${escAttr(ifid)}" options="" tags="" zoom="1" hidden>\n${sd}</tw-storydata>`;

// --- Assemble via template.html (the Makefile's exampleOutput.html recipe) ---
const tmpl = fs.readFileSync(path.join(REFDIR, 'template.html'), 'utf8');
const engineJs = fs.readFileSync(path.join(REFDIR, 'build', 'harlowe-min.js'), 'utf8');
const css = fs.readFileSync(path.join(REFDIR, 'build', 'harlowe-css.css'), 'utf8');
let archival = '(provenance unavailable)';
try { archival = fs.readFileSync(path.join(REFDIR, '.hg_archival.txt'), 'utf8').trim(); } catch {}

const provenance =
  '<!--\n  Generated by TestFiles/build-feature-coverage-html.js from feature-coverage.twee.\n' +
  '  Engine: locally-built reference Harlowe (branch/default):\n' +
  archival.split('\n').map(l => '    ' + l).join('\n') + '\n' +
  `  Start overridden to the generated _Index menu; the .twee's own start is "${startName}".\n-->\n`;

// NB: each replacement is a FUNCTION. A string replacement would have its `$&`/`$\``/`$'`/`$$`
// sequences interpreted as special patterns — and the minified engine (jQuery `$`, regex
// replacement literals) is full of them, which silently corrupts/duplicates the output.
const html = tmpl
  .replace(/\{\{STORY_NAME\}\}/g, () => escAttr(storyName))
  .replace('{{CSS}}', () => `<style title="Twine CSS">${css}</style>`)
  .replace('{{STORY_DATA}}', () => storydata)
  .replace('{{HARLOWE}}', () => `<script title="Twine engine code" data-main="harlowe">${engineJs}</script>`)
  .replace('<!DOCTYPE html>', () => '<!DOCTYPE html>\n' + provenance);

fs.writeFileSync(OUT, html);
console.log(`Wrote ${OUT}`);
console.log(`  story="${storyName}"  ifid=${ifid || '(none)'}  passages=${passages.length}  startnode=${indexPid} (_Index)`);
console.log(`  engine=${(engineJs.length / 1024).toFixed(0)}KB  css=${(css.length / 1024).toFixed(0)}KB  total=${(html.length / 1024).toFixed(0)}KB`);
